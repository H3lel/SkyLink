//! Point the system resolver at the TUN, where leaf answers every query with
//! a fake IP and resolves the real name on the far side of the tunnel.
//!
//! * systemd-resolved (the stub at 127.0.0.53): per-link DNS + `~.` routing
//!   domain on the TUN. That state lives on the link, so it disappears with
//!   the device and needs no restore.
//! * Anything else: /etc/resolv.conf is swapped and restored afterwards; a
//!   backup in /run/nthlink lets a later run restore it after a crash.

use nthlink_common::tunnel::{TUN_DNS, TUN_NAME};
use std::fs;
use std::os::unix::ffi::OsStrExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

const RESOLV: &str = "/etc/resolv.conf";
const MARKER: &str = "# Generated by nthlink-core";

pub enum DnsMode {
    Resolved,
    ResolvConf,
    Unchanged,
}

impl DnsMode {
    pub fn describe(&self) -> &'static str {
        match self {
            DnsMode::Resolved => "systemd-resolved",
            DnsMode::ResolvConf => "resolv.conf",
            DnsMode::Unchanged => "unchanged",
        }
    }
}

fn state(name: &str) -> PathBuf {
    Path::new(crate::STATE_DIR).join(name)
}

fn run(cmd: &str, args: &[&str]) -> bool {
    Command::new(cmd)
        .args(args)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .map(|s| s.success())
        .unwrap_or(false)
}

fn uses_resolved_stub() -> bool {
    let text = fs::read_to_string(RESOLV).unwrap_or_default();
    text.lines().any(|l| {
        let mut p = l.split_whitespace();
        p.next() == Some("nameserver") && matches!(p.next(), Some("127.0.0.53") | Some("127.0.0.54"))
    })
}

fn setup_resolved() -> bool {
    run("resolvectl", &["dns", TUN_NAME, TUN_DNS])
        && run("resolvectl", &["domain", TUN_NAME, "~."])
        && {
            // Optional knobs; older systemd lacks some of them.
            let _ = run("resolvectl", &["default-route", TUN_NAME, "true"]);
            let _ = run("resolvectl", &["dnssec", TUN_NAME, "no"]);
            let _ = run("resolvectl", &["dnsovertls", TUN_NAME, "no"]);
            let _ = run("resolvectl", &["llmnr", TUN_NAME, "no"]);
            let _ = run("resolvectl", &["mdns", TUN_NAME, "no"]);
            let _ = run("resolvectl", &["flush-caches"]);
            true
        }
}

fn ours() -> String {
    format!("{MARKER} while connected; the original is restored on disconnect.\nnameserver {TUN_DNS}\noptions edns0\n")
}

fn write_resolv_conf() -> std::io::Result<()> {
    let meta = fs::symlink_metadata(RESOLV);
    let backup_file = state("resolv.conf.bak");
    let backup_link = state("resolv.conf.link");
    let current = fs::read_to_string(RESOLV).unwrap_or_default();
    if !current.starts_with(MARKER) && !backup_file.exists() && !backup_link.exists() {
        match &meta {
            Ok(m) if m.file_type().is_symlink() => {
                fs::write(&backup_link, fs::read_link(RESOLV)?.as_os_str().as_encoded_bytes())?;
            }
            Ok(_) => {
                fs::copy(RESOLV, &backup_file)?;
            }
            Err(_) => {
                fs::write(&backup_file, "")?;
            }
        }
    }
    let tmp = Path::new("/etc/.resolv.conf.nthlink");
    fs::write(tmp, ours())?;
    fs::rename(tmp, RESOLV)
}

/// `choice`: `auto` (default), `resolved`, `resolvconf` or `none`.
pub fn setup(choice: &str) -> DnsMode {
    match choice {
        "none" => return DnsMode::Unchanged,
        "resolved" => {
            if setup_resolved() {
                return DnsMode::Resolved;
            }
            crate::log("warn", "systemd-resolved could not be configured; falling back to resolv.conf");
        }
        "resolvconf" => {}
        _ => {
            if uses_resolved_stub() && setup_resolved() {
                return DnsMode::Resolved;
            }
        }
    }
    match write_resolv_conf() {
        Ok(()) => DnsMode::ResolvConf,
        Err(e) => {
            crate::log("warn", format!("could not redirect DNS ({e}); queries to on-link resolvers may bypass the tunnel"));
            DnsMode::Unchanged
        }
    }
}

/// Re-apply if a network manager overwrote our settings.
pub fn ensure(mode: &DnsMode) {
    match mode {
        DnsMode::ResolvConf => {
            let cur = fs::read_to_string(RESOLV).unwrap_or_default();
            if !cur.starts_with(MARKER) {
                // Whatever the manager wrote is the new "original".
                let _ = fs::remove_file(state("resolv.conf.bak"));
                let _ = fs::remove_file(state("resolv.conf.link"));
                let _ = write_resolv_conf();
            }
        }
        DnsMode::Resolved => {
            let out = Command::new("resolvectl").args(["dns", TUN_NAME]).output();
            if let Ok(o) = out {
                if !String::from_utf8_lossy(&o.stdout).contains(TUN_DNS) {
                    setup_resolved();
                }
            }
        }
        DnsMode::Unchanged => {}
    }
}

/// Undo `setup`, including after a crash of an earlier run.
pub fn restore() {
    if Path::new("/sys/class/net").join(TUN_NAME).exists() {
        let _ = run("resolvectl", &["revert", TUN_NAME]);
    }
    let backup_file = state("resolv.conf.bak");
    let backup_link = state("resolv.conf.link");
    let current_is_ours = fs::read_to_string(RESOLV).map(|s| s.starts_with(MARKER)).unwrap_or(false);
    if let Ok(target) = fs::read(&backup_link) {
        if current_is_ours {
            let target = std::ffi::OsStr::from_bytes(&target);
            let tmp = Path::new("/etc/.resolv.conf.nthlink");
            let _ = fs::remove_file(tmp);
            if std::os::unix::fs::symlink(target, tmp).is_ok() {
                let _ = fs::rename(tmp, RESOLV);
            }
        }
        let _ = fs::remove_file(&backup_link);
    } else if backup_file.exists() {
        if current_is_ours {
            let tmp = Path::new("/etc/.resolv.conf.nthlink");
            if fs::copy(&backup_file, tmp).is_ok() {
                let _ = fs::rename(tmp, RESOLV);
            }
        }
        let _ = fs::remove_file(&backup_file);
    }
}
